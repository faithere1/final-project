package com.aclsim.service;

import com.aclsim.model.Rule;
import java.util.List;

public class CiscoGeneratorService {

    public String generateConfig(List<Rule> rules) {
        StringBuilder sb = new StringBuilder();
        sb.append("! Cisco IOS Access-List Generated by ACL Simulator\n");
        sb.append("ip access-list extended AUTO_GENERATED_ACL\n");

        for (Rule rule : rules) {
            String action = rule.getAction().toLowerCase();
            String proto = rule.getProtocol().toLowerCase();
            if (proto.equals("any")) proto = "ip"; // Cisco uses 'ip' for any protocol

            String src = formatAddress(rule.getSourceIp());
            String dest = formatAddress(rule.getDestIp());
            String port = formatPort(rule.getDestPort());

            sb.append(String.format(" %s %s %s %s %s\n", action, proto, src, dest, port));
        }
        
        sb.append("exit\n");
        return sb.toString();
    }

    private String formatAddress(String addr) {
        if (addr.equalsIgnoreCase("ANY") || addr.equals("0.0.0.0")) return "any";
        
        // Handle CIDR (e.g., 192.168.1.0/24 -> 192.168.1.0 0.0.0.255)
        if (addr.contains("/")) {
            String[] parts = addr.split("/");
            String ip = parts[0];
            int prefix = Integer.parseInt(parts[1]);
            return ip + " " + cidrToWildcard(prefix);
        }
        
        // If it's already a Wildcard (has space), keep it
        if (addr.contains(" ")) return addr;

        // Otherwise, it's a single host
        return "host " + addr;
    }

    private String formatPort(String port) {
        if (port.equalsIgnoreCase("ANY") || port.equals("-1")) return "";
        if (port.contains("-")) {
            String[] parts = port.split("-");
            return "range " + parts[0] + " " + parts[1];
        }
        return "eq " + port;
    }

    private String cidrToWildcard(int prefix) {
        int mask = 0xffffffff << (32 - prefix);
        int wildcard = ~mask;
        return String.format("%d.%d.%d.%d",
            (wildcard >> 24) & 0xff,
            (wildcard >> 16) & 0xff,
            (wildcard >> 8) & 0xff,
            wildcard & 0xff);
    }
}